from __future__ import annotations

import asyncio
import json
from pathlib import Path

from doorboard_simulator.scenarios import (
    ScenarioRunner,
    available_scenarios,
    load_scenario,
    result_to_json,
    run_scenario_name,
    scenario_path,
)


def test_all_required_scenarios_have_golden_logs(tmp_path: Path) -> None:
    expected_names = {
        "basic-bell",
        "camera-unavailable",
        "double-press-abuse",
        "esp32-silent",
        "full-happy-path",
        "hailo-down-known-visitor",
        "identity-churn-abuse",
        "known-visitor",
        "nas-outage",
        "nuc-outage",
        "press-during-recording",
        "storage-low",
        "unknown-visitor",
    }

    assert set(available_scenarios()) == expected_names

    golden_dir = Path(__file__).parent / "golden"
    for scenario_name in sorted(expected_names):
        result = asyncio.run(
            run_scenario_name(
                scenario_name,
                artifact_root=tmp_path / scenario_name,
            )
        )
        expected = json.loads((golden_dir / f"{scenario_name}.json").read_text(encoding="utf-8"))
        assert json.loads(result_to_json(result)) == expected


