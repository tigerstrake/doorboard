def test_hailo_down_yields_zero_personalised_behaviour(tmp_path: Path) -> None:
    runner = ScenarioRunner(artifact_root=tmp_path)
    result = asyncio.run(runner.run(load_scenario(scenario_path("hailo-down-known-visitor"))))
    types = [event["type"] for event in result.log]

    assert "vision.face_visible" in types
    assert "vision.identity_stable" not in types
    assert "door.profile_update" not in types
    pressed = next(event for event in result.log if event["type"] == "door.button_pressed")
    assert pressed["payload"]["had_cached_profile"] is False
    assert pressed["payload"]["profile_id"] is None
    assert not any(
        effect.startswith("personalized_feedback") for effect in runner.esp32.side_effects
    )
    assert "generic_feedback" in runner.esp32.side_effects


def test_silent_pi_puts_the_esp32_into_fallback(tmp_path: Path) -> None:
    result = asyncio.run(run_scenario_name("esp32-silent", artifact_root=tmp_path))
    health = [event for event in result.log if event["type"] == "door.controller_health"]

    # Heartbeat at 1 s (alive), nothing until 6.5 s (past the 5 s timeout), Pi back at 7 s.
    assert [event["payload"]["fallback_active"] for event in health] == [False, True, False]
    pressed = next(event for event in result.log if event["type"] == "door.button_pressed")
    assert pressed["monotonic_ms"] == 6600  # the button still works while the Pi is away


def test_camera_down_keeps_the_button_and_records_nothing(tmp_path: Path) -> None:
    result = asyncio.run(run_scenario_name("camera-unavailable", artifact_root=tmp_path))
    types = [event["type"] for event in result.log]

    assert "door.button_pressed" in types
    assert "media.recording_started" not in types
    assert "media.recording_finalized" not in types
    degraded = next(event for event in result.log if event["type"] == "system.service_health")
    assert degraded["payload"]["service"] == "door-media"
    assert degraded["payload"]["status"] == "degraded"


def test_fake_media_writes_placeholder_with_real_checksum(tmp_path: Path) -> None:
    result = asyncio.run(run_scenario_name("basic-bell", artifact_root=tmp_path))
    finalized = next(event for event in result.log if event["type"] == "media.recording_finalized")
    path = tmp_path / finalized["payload"]["path"]

    assert path.exists()
    assert path.stat().st_size == finalized["payload"]["size_bytes"]
